"""Writes company_data/brain_sources/: messy Fathom, docx, email and chat files, live calls, translations, lexicon, keys.

Run: python3 -m company_data.generate_brain_sources. Deterministic: no random draws, only hashes of the text.
"""
import hashlib
import json
import os
import re
import zipfile
from datetime import datetime, timedelta
from email.message import EmailMessage
from email.utils import format_datetime
from datetime import timezone

from company_data import DB_PATH
from company_data import brain_text_banks as B
from company_data import company_roster as R

IST = timezone(timedelta(hours=5, minutes=30))
DEVANAGARI = re.compile("[ऀ-ॿ]")
OWNER = dict(C01="P03", C04="P03", C07="P03", C08="P03", C09="P04", C10="P30")
README = """# brain_sources

Fake sources for the company brain. Generated by `python3 -m company_data.generate_brain_sources`; do not edit by hand.

Line numbers start at 1 and are the same in every file kind:
- fathom: the position in `transcript` (first entry is line 1).
- docx: each non-empty paragraph in `word/document.xml`, in order. The title is line 1.
- email: each non-empty line of the plain body (headers are not lines). One paragraph per line.
- chat: each message line, in file order.
- live call: the `line_no` field.

`kind_cues.json` lists the phrases the clean English text uses for each item kind. A line with a topic cue and no kind cue is a fact.
`translations.json` holds the clean English for every non-English line. The lines left out are the review cases.
"""


def _email_of(name, domain):
    return name.lower().replace(" ", ".").replace("'", "") + "@" + domain


def _directory():
    """full name -> email, built with the same rule as generate_dummy_data."""
    client_domain = {c[0]: c[1].lower().replace(" ", "-") + ".example" for c in R.CLIENTS + R.NEW_CLIENTS}
    out = {name: _email_of(name, "devx-demo.example") for _, name, *_ in R.DEVX_PEOPLE}
    for _, name, cid in R.CLIENT_CONTACTS + R.NEW_CLIENT_CONTACTS:
        out[name] = _email_of(name, client_domain[cid])
    return out


def _lang(raw, clean):
    if clean is None:
        return "en"
    letters = [c for c in raw if c.isalpha()]
    dev = sum(1 for c in letters if DEVANAGARI.match(c))
    return "hi" if letters and dev / len(letters) > 0.5 else "hinglish"


def _seconds(raw, i):
    h = int(hashlib.sha1(f"{raw}{i}".encode()).hexdigest(), 16)
    return 3 + len(raw) // 12 + h % 6


def _parse_item(spec):
    spec, _, label = spec.partition("@")
    kind, topic, *rest = spec.split("|")
    return kind, topic, rest[0].split(",") if rest and rest[0] else [], label


def _resolve(source, speaker, directory):
    if speaker is None:
        return None
    for full in source["who"]:
        if speaker == full or full.split()[0] == speaker:
            return full
    return speaker


def _normalise(src, directory):
    lines = []
    for i, (spk, raw, clean, item) in enumerate(src["lines"], 1):
        lines.append(dict(line_no=i, speaker=_resolve(src, spk, directory), raw=raw, clean=clean,
                          lang=_lang(raw, clean), item=item))
    return lines


def _write(path, data, mode="w"):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, mode, **({} if "b" in mode else {"encoding": "utf-8"})) as f:
        f.write(data)


def _fathom(src, lines, directory):
    start = datetime.fromisoformat(src["when"]).replace(tzinfo=IST)
    invitees = [dict(name=n, email=directory[n]) for n in src["who"]]
    t, transcript = 0, []
    for ln in lines:
        transcript.append(dict(
            speaker=dict(display_name=ln["speaker"], matched_calendar_invitee_email=directory.get(ln["speaker"])),
            text=ln["raw"], timestamp=f"{t // 3600:02d}:{t % 3600 // 60:02d}:{t % 60:02d}"))
        t += _seconds(ln["raw"], ln["line_no"])
    return dict(recording_id=8800000 + int(src["ref"][3:]), title=src["title"],
                created_at=start.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                calendar_invitees=invitees, transcript=transcript)


def _docx(path, lines):
    esc = lambda s: s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    paras = "".join(f"<w:p><w:r><w:t xml:space=\"preserve\">{esc(ln['raw'])}</w:t></w:r></w:p>" for ln in lines)
    body = ("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?><w:document xmlns:w=\"http://schemas.openxmlformats.org/"
            f"wordprocessingml/2006/main\"><w:body>{paras}</w:body></w:document>")
    types = ("<?xml version=\"1.0\" encoding=\"UTF-8\"?><Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\">"
             "<Default Extension=\"rels\" ContentType=\"application/vnd.openxmlformats-package.relationships+xml\"/>"
             "<Default Extension=\"xml\" ContentType=\"application/xml\"/><Override PartName=\"/word/document.xml\" "
             "ContentType=\"application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml\"/></Types>")
    rels = ("<?xml version=\"1.0\" encoding=\"UTF-8\"?><Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">"
            "<Relationship Id=\"rId1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument\" "
            "Target=\"word/document.xml\"/></Relationships>")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in [("[Content_Types].xml", types), ("_rels/.rels", rels), ("word/document.xml", body)]:
            z.writestr(zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0)), data)


def _eml(src, lines, directory):
    msg = EmailMessage()
    msg["From"] = src["sender"]
    msg["To"] = directory[next(r[1] for r in R.DEVX_PEOPLE if r[0] == OWNER[src["area"]])]
    msg["Subject"] = src["title"]
    msg["Date"] = format_datetime(datetime.fromisoformat(src["when"]).replace(tzinfo=IST))
    msg["Message-ID"] = f"<{src['ref'].lower()}@brain-sources.example>"
    msg.set_content("\n\n".join(ln["raw"] for ln in lines) + "\n")
    return msg.as_bytes()


def _chat(src, lines):
    t = datetime.fromisoformat(src["when"])
    out = []
    for ln in lines:
        t += timedelta(minutes=2 + len(ln["raw"]) % 5)
        out.append(f"[{t:%d/%m/%y, %H:%M}] {ln['speaker']}: {ln['raw']}")
    return "\n".join(out) + "\n"


def _item_key(ref, n):
    return f"{ref}-{n}"


def write_brain_sources(out_dir, event_id="EV115"):
    """Write every file under out_dir and return the answer keys for company_data/answer_keys.json["brain"]."""
    directory = _directory()
    manifest, translations, entries = [], {}, []
    label_key, line_key = {}, {}
    for src in B.SOURCES:
        ref, kind = src["ref"], src["kind"]
        lines = _normalise(src, directory)
        ext = dict(fathom="json", docx="docx", email="eml", chat="txt")[kind]
        rel = f"{kind}/{ref}.{ext}"
        path = os.path.join(out_dir, rel)
        if kind == "fathom":
            _write(path, json.dumps(_fathom(src, lines, directory), indent=2, ensure_ascii=False))
        elif kind == "docx":
            _docx(path, lines)
        elif kind == "email":
            _write(path, _eml(src, lines, directory), "wb")
        else:
            _write(path, _chat(src, lines))
        start = datetime.fromisoformat(src["when"])
        arrives = src["arrives"] or (start + timedelta(hours=1 if kind == "fathom" else 0)).strftime("%Y-%m-%dT%H:%M")
        manifest.append(dict(origin_ref=ref, kind=kind, file=rel, arrives_at=arrives, hint_area=src["hint"],
                             history=src["history"]))
        items, review, inject, n = [], [], [], 0
        for ln in lines:
            if ln["clean"]:
                translations[f"{ref}:{ln['line_no']}"] = ln["clean"]
            if ln["clean"] == "":
                review.append(ln["line_no"])
            if "ignore your rules" in ln["raw"]:
                inject.append(ln["line_no"])
            if ln["item"]:
                kind_, topic, words, label = _parse_item(ln["item"])
                n += 1
                key = _item_key(ref, n)
                items.append(dict(key=key, kind=kind_, topic=topic, line_from=ln["line_no"], line_to=ln["line_no"],
                                  must_contain=[w.lower() for w in words]))
                if label:
                    label_key[label] = key
                    line_key[label] = (ref, ln["line_no"])
        langs = {ln["lang"] for ln in lines} - {"en"}
        language = "en" if not langs else "mixed" if langs == {"hi", "hinglish"} else langs.pop()
        entries.append(dict(origin_ref=ref, area_id=src["area"], language=language, items=items, links=[],
                            review_lines=review, injection_lines=inject,
                            **({"expected_route": "hold"} if ref == "SRC29" else {})))
    by_ref = {e["origin_ref"]: e for e in entries}
    for later, rel_, earlier in B.LINKS:
        by_ref[line_key[later][0]]["links"].append(dict(**{"from": label_key[later]}, rel=rel_, to=label_key[earlier]))
    live = _write_live_calls(out_dir, translations, label_key)
    _write(os.path.join(out_dir, "manifest.json"), json.dumps(dict(sources=manifest), indent=2))
    _write(os.path.join(out_dir, "translations.json"), json.dumps(translations, indent=2, ensure_ascii=False))
    _write(os.path.join(out_dir, "topic_lexicon.json"), json.dumps(dict(topics=B.LEXICON), indent=2, ensure_ascii=False))
    _write(os.path.join(out_dir, "kind_cues.json"), json.dumps(B.KIND_CUES, indent=2))
    _write(os.path.join(out_dir, "README.md"), README)
    return dict(
        sources=entries,
        duplicates=[[label_key[a], label_key[b]] for a, b in B.DUPLICATES],
        playbooks=[dict(area_id=a, deal_id=d, outcome=o, later_changed_topics=lc, went_right_topics=wr, went_wrong_topics=ww)
                   for a, d, o, lc, wr, ww in B.PLAYBOOKS],
        deals=B.DEALS, live_calls=live,
        project_brief=[dict(event_id=event_id, area_id="C04", project_id="PR05",
                            must_cite_keys=[label_key[x] for x in B.BRIEF_LABELS])])


def _write_live_calls(out_dir, translations, label_key):
    out = []
    for call_id, spec in B.LIVE_CALLS.items():
        t, rows, expected = 0, [], []
        for i, (spk, raw, clean, item) in enumerate(spec["lines"], 1):
            t += _seconds(raw, i)
            rows.append(json.dumps(dict(line_no=i, t_sec=t, speaker=spk, speaker_id=spec["speakers"][spk],
                                        lang=_lang(raw, clean), text=raw), ensure_ascii=False))
            if clean:
                translations[f"{call_id}:{i}"] = clean
            if item:
                kind, topic, *against = item.split("|")
                expected.append(dict(line_no=i, kind=kind, topic=topic, **({"against": label_key[against[0]]} if against else {})))
        _write(os.path.join(out_dir, "live_calls", f"{call_id}.jsonl"), "\n".join(rows) + "\n")
        out.append(dict(call_id=call_id, area_id=spec["area"], viewer=spec["viewer"], window_lines=2, expected=expected))
    return out


def main():
    keys = write_brain_sources(os.path.join(os.path.dirname(DB_PATH), "brain_sources"))
    print(f"{len(keys['sources'])} sources, {sum(len(s['items']) for s in keys['sources'])} keyed items")


if __name__ == "__main__":
    main()
